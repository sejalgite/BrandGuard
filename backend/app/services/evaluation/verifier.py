"""
app/services/evaluation/verifier.py
Finding Quality Verification Engine (Phase 7).
Enforces the core BrandGuard principle: No Citation, No Flag.
Verifies snippet offsets, cited entity validity, active status, expiration,
tenant boundary isolation, confidence/severity validity, and duplicate suppression.
"""
import uuid
from datetime import datetime, date, timezone
from typing import List, Dict, Any, Tuple, Optional
from sqlalchemy.orm import Session

from app.models.finding import Finding, SeverityLevel, DetectionCategory, FindingStatus
from app.models.constitution import BrandRule, FactRegistry, TermBank, BrandAsset, EntityStatus


class FindingVerificationReport:
    """Detailed verification metrics for a set of findings."""
    def __init__(self):
        self.total_findings: int = 0
        self.verified_findings: int = 0
        self.rejected_findings: int = 0
        self.reasons: List[Dict[str, Any]] = []
        self.verified_list: List[Finding] = []

    @property
    def verification_rate(self) -> float:
        if self.total_findings == 0:
            return 1.0
        return round(self.verified_findings / self.total_findings, 4)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_findings": self.total_findings,
            "verified_findings": self.verified_findings,
            "rejected_findings": self.rejected_findings,
            "verification_rate": self.verification_rate,
            "rejections": self.reasons,
        }


class FindingQualityVerifier:
    """
    Automated gate verifying that every finding generated by the analysis engine
    meets enterprise quality, evidence snippet precision, and constitution integrity standards.
    """

    @staticmethod
    def verify_finding(
        db: Session,
        finding: Finding,
        source_text: str,
        current_time: Optional[datetime] = None
    ) -> Tuple[bool, Optional[str]]:
        """
        Verify an individual finding.
        Returns (is_valid, rejection_reason).
        """
        now = current_time or datetime.now(timezone.utc)
        today = now.date() if isinstance(now, datetime) else date.today()

        # 1. Evidence Snippet Non-Empty
        snippet = (finding.flagged_snippet or "").strip()
        if not snippet:
            return False, "Evidence snippet is empty"

        # 2. Source Text Containment & Offset Consistency
        if source_text:
            if snippet.lower() not in source_text.lower():
                return False, f"Flagged snippet '{snippet}' not found in source text"

            if finding.char_offset_start is not None and finding.char_offset_end is not None:
                if finding.char_offset_start < 0 or finding.char_offset_end > len(source_text):
                    return False, "Snippet character offsets exceed source text boundaries"
                if finding.char_offset_start >= finding.char_offset_end:
                    return False, "Snippet character start offset must be less than end offset"

        # 3. Citation Integrity ("No Citation, No Flag")
        has_rule = finding.rule_id is not None
        has_fact = finding.fact_id is not None
        has_term = finding.term_id is not None
        has_asset = finding.asset_id is not None

        if not (has_rule or has_fact or has_term or has_asset or finding.cited_code):
            return False, "No citation: Finding lacks valid reference to rule, fact, term, asset, or cited code"

        # 4. Constitution Entity Verification & Tenant Isolation
        org_id = finding.organization_id

        if finding.rule_id:
            rule = db.query(BrandRule).filter(
                BrandRule.id == finding.rule_id,
                BrandRule.organization_id == org_id
            ).first()
            if not rule:
                return False, f"Cited BrandRule {finding.rule_id} not found in tenant organization"
            if rule.status != EntityStatus.ACTIVE:
                return False, f"Cited BrandRule {rule.rule_code} is not ACTIVE (status: {rule.status})"

        if finding.fact_id:
            fact = db.query(FactRegistry).filter(
                FactRegistry.id == finding.fact_id,
                FactRegistry.organization_id == org_id
            ).first()
            if not fact:
                return False, f"Cited Fact {finding.fact_id} not found in tenant organization"
            if fact.status != EntityStatus.ACTIVE:
                return False, f"Cited Fact {fact.fact_code} is not ACTIVE (status: {fact.status})"
            # Check fact expiration
            if fact.expiry_date and fact.expiry_date < today:
                return False, f"Cited Fact {fact.fact_code} expired on {fact.expiry_date}"

        if finding.term_id:
            term = db.query(TermBank).filter(
                TermBank.id == finding.term_id,
                TermBank.organization_id == org_id
            ).first()
            if not term:
                return False, f"Cited TermBank entry {finding.term_id} not found in tenant organization"
            if term.status != EntityStatus.ACTIVE:
                return False, f"Cited TermBank entry '{term.term}' is not ACTIVE"

        if finding.asset_id:
            asset = db.query(BrandAsset).filter(
                BrandAsset.id == finding.asset_id,
                BrandAsset.organization_id == org_id
            ).first()
            if not asset:
                return False, f"Cited BrandAsset {finding.asset_id} not found in tenant organization"
            if asset.status != EntityStatus.ACTIVE:
                return False, f"Cited BrandAsset '{asset.name}' is not ACTIVE"

        # 5. Severity & Confidence Bounds
        if finding.confidence is not None:
            if not (0.0 <= finding.confidence <= 1.0):
                return False, f"Confidence {finding.confidence} out of valid range [0.0, 1.0]"

        # 6. Suggested Correction Distinctness
        if finding.suggested_correction:
            if finding.suggested_correction.strip().lower() == snippet.lower():
                return False, "Suggested correction is identical to the flagged violation snippet"

        return True, None

    @classmethod
    def verify_and_filter_findings(
        cls,
        db: Session,
        findings: List[Finding],
        source_text: str,
        current_time: Optional[datetime] = None
    ) -> FindingVerificationReport:
        """
        Verify a collection of findings, filtering out duplicates and invalid citations.
        """
        report = FindingVerificationReport()
        report.total_findings = len(findings)

        seen_keys = set()

        for f in findings:
            is_valid, reason = cls.verify_finding(db, f, source_text, current_time)
            if not is_valid:
                report.rejected_findings += 1
                report.reasons.append({
                    "finding_id": str(f.id) if hasattr(f, "id") and f.id else None,
                    "snippet": f.flagged_snippet,
                    "category": f.category.value if hasattr(f.category, "value") else str(f.category),
                    "reason": reason
                })
                continue

            # Duplicate Suppression
            # Deduplicate by (category, snippet.lower(), cited_code, char_offset_start)
            dedup_key = (
                f.category.value if hasattr(f.category, "value") else str(f.category),
                f.flagged_snippet.strip().lower(),
                f.cited_code or "",
                f.char_offset_start
            )
            if dedup_key in seen_keys:
                report.rejected_findings += 1
                report.reasons.append({
                    "finding_id": str(f.id) if hasattr(f, "id") and f.id else None,
                    "snippet": f.flagged_snippet,
                    "category": dedup_key[0],
                    "reason": "Duplicate finding suppressed"
                })
                continue

            seen_keys.add(dedup_key)
            report.verified_findings += 1
            report.verified_list.append(f)

        return report
